"""Common French words (by frequency), words by CEFR level, and everyday phrases, with each one's card status.

app/data/word_bank.json and app/data/levels.json are generated by scripts/build_word_bank.py
from Lexique 3.83 (CC BY-SA 4.0) and FLELex (CC BY-NC-SA 4.0); app/data/phrases.json is a
hand-written list.
"""

import json
import unicodedata
from functools import cache
from pathlib import Path

from sqlalchemy.orm import Session

from app.services.text_processor import CardIndex, match_status

DATA_DIR = Path(__file__).resolve().parent.parent / "data"
MAIN_POS = ("noun", "verb", "adjective", "adverb")
COVERAGE_BANDS = (100, 500, 1000, 2000, 5000)
LEVELS = ("A1", "A2", "B1", "B2", "C1", "C2")


@cache
def _words() -> list[dict]:
    return json.loads((DATA_DIR / "word_bank.json").read_text(encoding="utf-8"))


@cache
def _levels() -> list[dict]:
    return json.loads((DATA_DIR / "levels.json").read_text(encoding="utf-8"))


@cache
def _phrases() -> list[dict]:
    return json.loads((DATA_DIR / "phrases.json").read_text(encoding="utf-8"))


def _fold(text: str) -> str:
    """Accent- and case-insensitive search key, so "ecole" finds "école"."""
    return "".join(c for c in unicodedata.normalize("NFD", text) if not unicodedata.combining(c)).lower()


def _with_status(index: CardIndex, entries: list[dict]) -> list[dict]:
    return [{**entry, **match_status(index.match_text(entry["word"], forms=False))} for entry in entries]


def _page(words: list[dict], *, offset: int, limit: int, q: str, pos: str | None, hide_known: bool) -> dict:
    query = _fold(q.strip())
    matches = [
        w
        for w in words
        if (not query or query in _fold(w["word"]))
        and (pos is None or (w["pos"][0] == pos if pos != "other" else w["pos"][0] not in MAIN_POS))
        and not (hide_known and w["in_database"])
    ]
    return {"total": len(matches), "items": matches[offset : offset + limit]}


def bank_words(db: Session, *, offset: int, limit: int, q: str = "", pos: str | None = None, hide_known: bool = False) -> dict:
    words = _with_status(CardIndex(db), _words())
    coverage = [
        {"top": band, "known": sum(1 for w in words[:band] if w["in_database"])}
        for band in COVERAGE_BANDS
        if band <= len(words)
    ]
    return {**_page(words, offset=offset, limit=limit, q=q, pos=pos, hide_known=hide_known), "coverage": coverage}


def level_words(
    db: Session, *, level: str, offset: int, limit: int, q: str = "", pos: str | None = None, hide_known: bool = False
) -> dict:
    words = _with_status(CardIndex(db), _levels())
    coverage = [
        {
            "level": lv,
            "total": sum(1 for w in words if w["level"] == lv),
            "known": sum(1 for w in words if w["level"] == lv and w["in_database"]),
        }
        for lv in LEVELS
    ]
    in_level = [w for w in words if w["level"] == level]
    return {**_page(in_level, offset=offset, limit=limit, q=q, pos=pos, hide_known=hide_known), "coverage": coverage}


def bank_phrases(db: Session) -> list[dict]:
    index = CardIndex(db)
    return [
        {
            "category": group["category"],
            "phrases": [
                {"text": text, "translation": translation, **match_status(index.match_text(text))}
                for text, translation in group["phrases"]
            ],
        }
        for group in _phrases()
    ]
